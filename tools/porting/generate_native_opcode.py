"""Generate the checked-in native opcode catalog; --check verifies reproducibility.

Uses the compact, statically verified RTTI/singleton mapping only. No game
execution or dependency beyond Python's standard library is required.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'tools/porting/data/opcode_mapping_2976_3527.json'
# 3527 -> 3663 by RTTI name (troc_map.py on the 3663 exe, 2026-11-13; its build labels say 2976/3527, as every
# troc_map.py output does: the 'old' side is troc_messages_3527.csv). 3576 shares 3527's catalogue.
SOURCE_3663 = ROOT / 'tools/porting/data/opcode_mapping_3576_3663.json'
VERSION = 1


def render():
    data = json.loads(SOURCE.read_text(encoding='utf-8'))
    assert data['source_build'] == '1.0.0.2976' and data['target_build'] == '1.0.0.3527'
    assert data['stats']['unresolved'] == 0
    shared = data['opcode_mapping']
    removed = data['unmapped_old_opcodes']
    added = data['added_opcodes']
    assert len(shared) == 1108 and len(removed) == 7 and len(added) == 67
    assert sorted(r['name'] for r in added) == data['new_names']
    old = [(r['old'], r['old'], r['kind'], r['name']) for r in shared + removed]
    new = [(r['old'], r['new'], r['kind'], r['name']) for r in shared]
    new += [(0x8000 | r['new'], r['new'], r['kind'], r['name']) for r in added]
    for rows in (old, new):
        assert len({r[0] for r in rows}) == len(rows)
        assert len({r[1] for r in rows}) == len(rows)
        assert len({r[3] for r in rows}) == len(rows)
        assert all(1000 <= r[1] < 0x8000 and 0 < r[0] <= 0xFFFF for r in rows)
        rows.sort(key=lambda row: row[1])
    assert all(r[0] < 0x8000 for r in old)
    # 1.0.0.3663: every 3527 message keeps its logical ID under its new native one (1066 of 1175 renumbered, kinds
    # unchanged); the 4 messages new in 3663 get 0xC000 | native ID (3527's additions use 0x8000 | native, < 0xC000).
    d3663 = json.loads(SOURCE_3663.read_text(encoding='utf-8'))
    assert d3663['stats']['unresolved'] == 0 and len(d3663['added_opcodes']) == 4
    renum = {r['name']: r for r in d3663['opcode_mapping']}
    gone = {r['name'] for r in d3663['unmapped_old_opcodes']}
    v3663 = []
    for logical, native, kind, name in new:
        assert name not in gone, name
        r = renum[name]
        assert r['old'] == native and r['kind'] == kind, name
        v3663.append((logical, r['new'], kind, name))
    v3663 += [(0xC000 | r['new'], r['new'], r['kind'], r['name']) for r in d3663['added_opcodes']]
    assert all(r['new'] < 0x4000 for r in d3663['added_opcodes'])
    assert len({r[0] for r in v3663}) == len({r[1] for r in v3663}) == len({r[3] for r in v3663}) == len(v3663)
    assert all(1000 <= r[1] < 0x8000 for r in v3663)
    v3663.sort(key=lambda row: row[1])
    canonical = json.dumps({'version': VERSION, '2976': old, '3527': new, '3663': v3663}, separators=(',', ':'),
                           ensure_ascii=True)
    digest = hashlib.sha256(canonical.encode('ascii')).hexdigest()
    header = ('// Generated by tools/porting/generate_native_opcode.py; do not edit.\n'
              '#pragma once\n#include <cstdint>\n\nnamespace cdmp::native_opcode {\n'
              f'inline constexpr uint32_t kMappingVersion = {VERSION};\n'
              f'inline constexpr uint64_t kMappingFingerprint = 0x{digest[:16]}ULL;\n'
              f'// Full canonical SHA-256: {digest}\n'
              '} // namespace cdmp::native_opcode\n')
    lines = ['// Generated by tools/porting/generate_native_opcode.py; do not edit.',
             '// Logical 2976 IDs; verified 3527 additions use 0x8000 | native ID, 3663 additions 0xC000 | native ID.']
    for build, rows in ((2976, old), (3527, new), (3663, v3663)):
        lines.append(f'constexpr std::array<Entry, {len(rows)}> kEntries{build}{{{{')
        lines += [f'    {{{logical}, {native}, {kind}U, {json.dumps(name)}}},' for logical, native, kind, name in rows]
        lines.append('}};')
    for build, rows in ((3527, new), (3663, v3663)):
        order = sorted(range(len(rows)), key=lambda i: rows[i][0])
        lines.append(f'constexpr std::array<uint16_t, {len(order)}> kLogicalOrder{build}{{{{')
        lines += ['    ' + ', '.join(map(str, order[i:i + 20])) + ',' for i in range(0, len(order), 20)]
        lines.append('}};')
    return {'native_opcode_mapping_id.h': header, 'native_opcode_table.inc': '\n'.join(lines) + '\n'}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, content in render().items():
        path = ROOT / 'src/common' / name
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                raise SystemExit(f'Stale generated file: {path}')
        else:
            path.write_text(content, encoding='utf-8', newline='\n')
        print(('Checked ' if args.check else 'Wrote ') + str(path))


if __name__ == '__main__':
    main()
